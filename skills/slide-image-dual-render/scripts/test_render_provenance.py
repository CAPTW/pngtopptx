#!/usr/bin/env python3
"""Test-only OOXML identity verifier. No production gates or crop exceptions."""
import hashlib
import json
import sys
import zipfile
import xml.etree.ElementTree as ET
from validate_pptx_package import resolve_target

NS = {'p': 'http://schemas.openxmlformats.org/presentationml/2006/main',
      'a': 'http://schemas.openxmlformats.org/drawingml/2006/main',
      'r': 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'}

def digest(data):
    return hashlib.sha256(data).hexdigest()

def extract(pptx):
    with zipfile.ZipFile(pptx) as package:
        root = ET.fromstring(package.read('ppt/slides/slide1.xml'))
        rels_path = 'ppt/slides/_rels/slide1.xml.rels'
        rels = {r.attrib['Id']: r.attrib for r in ET.fromstring(package.read(rels_path))}
        found = []
        for shape in root.find('p:cSld/p:spTree', NS):
            if shape.tag not in {f"{{{NS['p']}}}sp", f"{{{NS['p']}}}pic"}:
                continue
            xfrm = shape.find('p:spPr/a:xfrm', NS)
            off, ext = xfrm.find('a:off', NS), xfrm.find('a:ext', NS)
            row = {'geometryEmu': [int(off.attrib['x']), int(off.attrib['y']),
                                   int(ext.attrib['cx']), int(ext.attrib['cy'])]}
            if shape.tag == f"{{{NS['p']}}}pic":
                rid = shape.find('p:blipFill/a:blip', NS).attrib[f"{{{NS['r']}}}embed"]
                rel = rels[rid]
                assert rel['Type'].endswith('/image') and rel.get('TargetMode') != 'External'
                media = resolve_target(rels_path, rel['Target'])
                row.update(kind='image', sha256=digest(package.read(media)), media=media)
            else:
                body = shape.find('p:txBody', NS)
                if body is None:
                    row['kind'] = 'shape'
                else:
                    paragraphs = []
                    for paragraph in body.findall('a:p', NS):
                        paragraphs.append(''.join('\n' if child.tag == f"{{{NS['a']}}}br" else (child.text or '')
                                                  for child in paragraph.iter()
                                                  if child.tag in {f"{{{NS['a']}}}t", f"{{{NS['a']}}}br"}))
                    text = '\n'.join(paragraphs)
                    row.update(kind='text', text=text, sha256=digest(text.encode('utf-8')))
            found.append(row)
        return found

def verify(pptx, manifest, canonical_texts=None):
    actual = extract(pptx)
    expected = manifest['slides']['1']['objects']
    assert len(actual) == len(expected), f'object count mismatch: {len(actual)} != {len(expected)}'
    for i, (obj, emitted) in enumerate(zip(expected, actual)):
        # Independently project the recorded source-pixel box through the documented
        # inch rounding. Fixture uses the unchanged default 1672 x 941 canvas.
        expected_geometry = [round(round(obj[k] * scale, 3) * 914400)
                             for k, scale in [('x', 13.333 / 1672), ('y', 7.5 / 941),
                                              ('w', 13.333 / 1672), ('h', 7.5 / 941)]]
        assert expected_geometry == emitted['geometryEmu'], f'geometry mismatch at {i}'
        if obj['type'] == 'text':
            assert emitted['kind'] == 'text', f'native text missing at {i}'
            assert obj['representation'] == 'native-text' and obj['contentEditable'] is True
            assert obj['textContentSerialization'] == 'pptxgenjs-paragraph-text-v1'
            assert obj.get('textContentSha256') == emitted['sha256'], f'text identity mismatch at {i}'
        elif obj['type'] in {'image', 'icon'}:
            assert emitted['kind'] == 'image', f'image missing at {i}'
            assert obj['representation'] == 'raster-image' and obj['contentEditable'] is False
            assert obj.get('imageFileSha256') == emitted['sha256'], f'image identity mismatch at {i}'
        else:
            assert emitted['kind'] == 'shape', f'native shape missing at {i}'
    # A separate authored-content contract must not be generated by the producer's
    # projection. This strict test-only check does not forgive CRLF or whitespace.
    for index, canonical in (canonical_texts or {}).items():
        row = actual[int(index)]
        assert row['kind'] == 'text' and row['sha256'] == digest(canonical.encode('utf-8')), \
            f'canonical authored text mismatch at {index}'
    return actual

if __name__ == '__main__':
    if len(sys.argv) == 2:
        print(json.dumps(extract(sys.argv[1]), ensure_ascii=False))
    else:
        print(json.dumps(verify(sys.argv[1], json.load(open(sys.argv[2])),
                               json.load(open(sys.argv[3])) if len(sys.argv) > 3 else None), ensure_ascii=False))
